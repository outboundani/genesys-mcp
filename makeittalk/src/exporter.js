// Standalone export: turns a project manifest into a single-file Cloudflare
// Worker with zero dependencies - same MCP surface as the hosted endpoint, but
// running entirely in the user's own account with their own secrets. The
// generated code deliberately avoids template literals so nothing needs
// escaping here.

export function exportWorker(project, manifest) {
  const credEnvLines = (manifest.auth.fields || [])
    .map((f) => `//   ${credEnvName(f.key)}  - ${f.label}`)
    .join('\n');

  return `// ${manifest.server.name} - a standalone MCP server for ${manifest.server.base_url}
// Generated by makeittalk.dev from project "${project.name}" (${project.slug}).
//
// Deploy (zero dependencies):
//   1. Save this file as src/index.js in an empty folder.
//   2. Add wrangler.toml:
//        name = "${project.slug}-mcp"
//        main = "src/index.js"
//        compatibility_date = "2026-08-01"
//   3. Set secrets:
//        npx wrangler secret put MCP_AUTH_TOKEN     # any long random string; MCP clients present it as a Bearer token
${credEnvLines ? credEnvLines.replace(/^\/\//gm, '//        npx wrangler secret put').replace(/ {2}- .*$/gm, '') + '\n' : ''}//   4. npx wrangler deploy
//   5. Point any MCP client at https://<your-worker>/mcp with the token.
//
// Credential environment variables used at runtime:
${credEnvLines || '//   (none - this API needs no credentials)'}

const MANIFEST = ${JSON.stringify(manifest, null, 2)};

const ALLOW_DELETE = ${project.allow_delete ? 'true' : 'false'};
const PROTOCOL_VERSIONS = ['2025-06-18', '2025-03-26', '2024-11-05'];

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const path = url.pathname.replace(/\\/+$/, '') || '/';
    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: cors() });
    }
    if (path === '/' && request.method === 'GET') {
      return new Response(MANIFEST.server.name + ' - MCP server generated by makeittalk.dev. POST JSON-RPC to /mcp.', { headers: cors() });
    }
    if (path !== '/mcp' && path !== '/') return json({ error: 'Not found' }, 404);
    if (request.method !== 'POST') return json({ error: 'POST JSON-RPC to /mcp' }, 405);

    const auth = request.headers.get('Authorization') || '';
    if (!env.MCP_AUTH_TOKEN || auth !== 'Bearer ' + env.MCP_AUTH_TOKEN) {
      return json({ error: 'Unauthorized' }, 401);
    }

    let body;
    try { body = await request.json(); } catch { return json(rpcError(null, -32700, 'Parse error'), 400); }
    if (Array.isArray(body)) {
      const results = (await Promise.all(body.map((m) => handle(m, env)))).filter(Boolean);
      return results.length ? json(results) : new Response(null, { status: 202, headers: cors() });
    }
    const result = await handle(body, env);
    return result ? json(result) : new Response(null, { status: 202, headers: cors() });
  },
};

async function handle(msg, env) {
  if (!msg || typeof msg !== 'object' || msg.jsonrpc !== '2.0') return rpcError(msg && msg.id, -32600, 'Invalid JSON-RPC');
  const id = msg.id;
  if (id === undefined || id === null) return null;
  try {
    if (msg.method === 'initialize') {
      const req = msg.params && msg.params.protocolVersion;
      return rpcResult(id, {
        protocolVersion: PROTOCOL_VERSIONS.includes(req) ? req : PROTOCOL_VERSIONS[0],
        capabilities: { tools: {} },
        serverInfo: { name: MANIFEST.server.name, version: '1.0.0' },
        instructions: MANIFEST.server.description,
      });
    }
    if (msg.method === 'ping') return rpcResult(id, {});
    if (msg.method === 'tools/list') return rpcResult(id, { tools: toolDefs() });
    if (msg.method === 'tools/call') {
      return rpcResult(id, await callTool(env, msg.params && msg.params.name, (msg.params && msg.params.arguments) || {}));
    }
    return rpcError(id, -32601, 'Method not found: ' + msg.method);
  } catch (e) {
    return rpcError(id, -32603, 'Internal error: ' + e.message);
  }
}

function toolDefs() {
  const defs = MANIFEST.tools.map(function (t) {
    return { name: t.name, description: t.description, inputSchema: t.input_schema };
  });
  defs.push({
    name: 'api_call',
    description: 'Escape hatch: call any ' + MANIFEST.server.base_url + ' endpoint directly.' + (ALLOW_DELETE ? '' : ' DELETE is refused.'),
    inputSchema: {
      type: 'object',
      properties: {
        method: { type: 'string', enum: ALLOW_DELETE ? ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'] : ['GET', 'POST', 'PUT', 'PATCH'] },
        path: { type: 'string' },
        query: { type: 'object', additionalProperties: true },
        body: { type: 'object', additionalProperties: true },
      },
      required: ['method', 'path'],
      additionalProperties: false,
    },
  });
  return defs;
}

async function callTool(env, name, args) {
  let built;
  if (name === 'api_call') {
    const method = String(args.method || 'GET').toUpperCase();
    if (method === 'DELETE' && !ALLOW_DELETE) return errText('DELETE is refused on this server.');
    const u = new URL(MANIFEST.server.base_url + String(args.path || '/'));
    for (const k in (args.query || {})) u.searchParams.set(k, String(args.query[k]));
    built = {
      url: u.toString(), method: method, headers: {},
      body: method !== 'GET' && args.body ? JSON.stringify(args.body) : undefined,
    };
    if (built.body) built.headers['Content-Type'] = 'application/json';
  } else {
    const tool = MANIFEST.tools.find(function (t) { return t.name === name; });
    if (!tool) return errText('Unknown tool: ' + name);
    try { built = buildRequest(tool, args); } catch (e) { return errText(e.message); }
  }
  try {
    const headers = Object.assign({ Accept: 'application/json' }, built.headers);
    const authed = await applyAuth(env, built.url, headers);
    const res = await fetch(authed.url, { method: built.method, headers: authed.headers, body: built.body });
    const text = await res.text();
    let rendered = text;
    try { rendered = JSON.stringify(JSON.parse(text), null, 2); } catch (e) { /* not JSON */ }
    if (rendered.length > 60000) rendered = rendered.slice(0, 60000) + '\\n...[truncated]';
    return {
      content: [{ type: 'text', text: 'HTTP ' + res.status + ' ' + built.method + ' ' + new URL(built.url).pathname + '\\n' + rendered }],
      isError: !res.ok,
    };
  } catch (e) {
    return errText('Request failed: ' + e.message);
  }
}

function buildRequest(tool, args) {
  args = args || {};
  const used = new Set();
  const path = tool.request.path.replace(/\\{([a-z0-9_]+)\\}/gi, function (_, key) {
    if (args[key] === undefined || args[key] === null || args[key] === '') throw new Error('Missing required path parameter "' + key + '".');
    used.add(key);
    return encodeURIComponent(String(args[key]));
  });
  const url = new URL(MANIFEST.server.base_url + path);
  for (const k in (tool.request.query || {})) {
    const v = resolve(tool.request.query[k], args, used);
    if (v !== undefined && v !== null && v !== '') url.searchParams.set(k, String(v));
  }
  const headers = {};
  for (const k in (tool.request.headers || {})) {
    const v = resolve(tool.request.headers[k], args, used);
    if (v !== undefined && v !== null && v !== '') headers[k] = String(v);
  }
  let body;
  if (tool.request.method !== 'GET') {
    let payload;
    if (tool.request.body) payload = substitute(tool.request.body, args, used);
    else {
      payload = {};
      for (const k in args) if (!used.has(k)) payload[k] = args[k];
    }
    if (payload && Object.keys(payload).length) {
      if (tool.request.content_type === 'form') {
        headers['Content-Type'] = 'application/x-www-form-urlencoded';
        body = formEncode(payload, '', []);
      } else {
        headers['Content-Type'] = 'application/json';
        body = JSON.stringify(payload);
      }
    }
  } else {
    for (const k in args) {
      if (!used.has(k) && !url.searchParams.has(k) && args[k] !== undefined && args[k] !== null && args[k] !== '' && typeof args[k] !== 'object') {
        url.searchParams.set(k, String(args[k]));
      }
    }
  }
  return { url: url.toString(), method: tool.request.method, headers: headers, body: body };
}

function resolve(value, args, used) {
  if (typeof value === 'string' && value.charAt(0) === '$' && value.charAt(1) !== '$') {
    const key = value.slice(1);
    used.add(key);
    return args[key];
  }
  return value;
}

function substitute(node, args, used) {
  if (typeof node === 'string') {
    if (node === '$$rest') {
      const rest = {};
      for (const k in args) if (!used.has(k)) rest[k] = args[k];
      return rest;
    }
    return resolve(node, args, used);
  }
  if (Array.isArray(node)) return node.map(function (n) { return substitute(n, args, used); }).filter(function (n) { return n !== undefined; });
  if (node && typeof node === 'object') {
    const out = {};
    for (const k in node) {
      const v = substitute(node[k], args, used);
      if (v !== undefined) out[k] = v;
    }
    return out;
  }
  return node;
}

function formEncode(obj, prefix, pairs) {
  for (const k in obj) {
    const v = obj[k];
    if (v === undefined || v === null) continue;
    const key = prefix ? prefix + '[' + k + ']' : k;
    if (typeof v === 'object') formEncode(v, key, pairs);
    else pairs.push(encodeURIComponent(key) + '=' + encodeURIComponent(String(v)));
  }
  return pairs.join('&');
}

let cachedOauth = null;
async function applyAuth(env, url, headers) {
  const auth = MANIFEST.auth || { type: 'none' };
  const cred = function (key) { return env[${JSON.stringify(credEnvPrefix())} + key.toUpperCase()] || ''; };
  if (auth.type === 'none') return { url: url, headers: headers };
  if (auth.type === 'bearer') {
    headers[auth.header || 'Authorization'] = (auth.prefix != null ? auth.prefix : 'Bearer ') + requireCred(cred, ['token', 'api_key', 'key']);
    return { url: url, headers: headers };
  }
  if (auth.type === 'api_key_header') {
    headers[auth.header || 'X-API-Key'] = (auth.prefix || '') + requireCred(cred, ['api_key', 'token', 'key']);
    return { url: url, headers: headers };
  }
  if (auth.type === 'basic') {
    headers['Authorization'] = 'Basic ' + btoa(requireCred(cred, ['username', 'client_id']) + ':' + (cred('password') || cred('client_secret')));
    return { url: url, headers: headers };
  }
  if (auth.type === 'query_param') {
    const u = new URL(url);
    u.searchParams.set(auth.param || 'api_key', requireCred(cred, ['api_key', 'token', 'key']));
    return { url: u.toString(), headers: headers };
  }
  if (auth.type === 'oauth2_client_credentials') {
    if (!cachedOauth || cachedOauth.exp < Date.now()) {
      const params = new URLSearchParams({ grant_type: 'client_credentials' });
      if (auth.scopes) params.set('scope', auth.scopes);
      const res = await fetch(auth.token_url, {
        method: 'POST',
        headers: {
          Authorization: 'Basic ' + btoa(requireCred(cred, ['client_id']) + ':' + requireCred(cred, ['client_secret'])),
          'Content-Type': 'application/x-www-form-urlencoded',
        },
        body: params.toString(),
      });
      const data = await res.json();
      if (!res.ok || !data.access_token) throw new Error('OAuth2 token request failed (HTTP ' + res.status + ')');
      cachedOauth = { token: data.access_token, exp: Date.now() + Math.max(60, (data.expires_in || 3600) - 300) * 1000 };
    }
    headers['Authorization'] = 'Bearer ' + cachedOauth.token;
    return { url: url, headers: headers };
  }
  throw new Error('Unsupported auth type ' + auth.type);
}

function requireCred(cred, keys) {
  for (const k of keys) { const v = cred(k); if (v) return v; }
  throw new Error('Missing credential secret - set ' + ${JSON.stringify(credEnvPrefix())} + keys[0].toUpperCase() + ' with wrangler.');
}

function errText(text) { return { content: [{ type: 'text', text: 'Error: ' + text }], isError: true }; }
function cors() {
  return {
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type, Authorization, Mcp-Protocol-Version, Mcp-Session-Id',
  };
}
function json(data, status) {
  return new Response(JSON.stringify(data), { status: status || 200, headers: Object.assign({ 'Content-Type': 'application/json' }, cors()) });
}
function rpcResult(id, result) { return { jsonrpc: '2.0', id: id, result: result }; }
function rpcError(id, code, message) { return { jsonrpc: '2.0', id: id === undefined ? null : id, error: { code: code, message: message } }; }
`;
}

function credEnvPrefix() {
  return 'CRED_';
}

function credEnvName(key) {
  return `CRED_${key.toUpperCase()}`;
}
