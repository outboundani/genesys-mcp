// The universal MCP runtime. Every generated project is served at
// POST /mcp/<slug> as a stateless streamable-HTTP MCP server (same protocol
// surface as genesys-mcp / five9-mcp). Tools are executed straight from the
// project's manifest; credentials are decrypted only at call time.

import { buildRequest, applyAuth, invalidateOauthToken } from './manifest.js';
import { decryptJson } from './crypto.js';
import { checkMcpAuth, unauthorizedMcp } from './mcpoauth.js';
import { clampStr, json, now, monthKey } from './util.js';
import { planFor } from './plans.js';

const PROTOCOL_VERSIONS = ['2025-06-18', '2025-03-26', '2024-11-05'];
const RESPONSE_CHAR_LIMIT = 60000;

export async function handleMcp(request, env, ctx, slug) {
  const project = await env.DB.prepare('SELECT * FROM projects WHERE slug = ?').bind(slug).first();
  if (!project) return json({ error: `No MCP named "${slug}" here.` }, 404);
  if (request.method !== 'POST') {
    return json({ error: `This is an MCP endpoint - POST JSON-RPC to it, or point an MCP client at this URL.` }, 405);
  }
  if (!(await checkMcpAuth(request, env, project))) return unauthorizedMcp(request, slug);
  if (project.status !== 'ready' || !project.manifest) {
    return json({ error: `MCP "${slug}" is not ready yet (status: ${project.status}).` }, 409);
  }

  let body;
  try { body = await request.json(); } catch {
    return json(rpcError(null, -32700, 'Parse error: body must be JSON'), 400);
  }

  const cx = { env, ctx, project, manifest: JSON.parse(project.manifest) };
  if (Array.isArray(body)) {
    const results = (await Promise.all(body.map((m) => handleMessage(m, cx)))).filter(Boolean);
    return results.length ? json(results) : new Response(null, { status: 202 });
  }
  const result = await handleMessage(body, cx);
  return result ? json(result) : new Response(null, { status: 202 });
}

async function handleMessage(msg, cx) {
  if (!msg || typeof msg !== 'object' || msg.jsonrpc !== '2.0') {
    return rpcError(msg?.id ?? null, -32600, 'Invalid JSON-RPC 2.0 request');
  }
  const { id, method, params } = msg;
  if (id === undefined || id === null) return null; // notifications get no body

  try {
    switch (method) {
      case 'initialize': {
        const requested = params?.protocolVersion;
        return rpcResult(id, {
          protocolVersion: PROTOCOL_VERSIONS.includes(requested) ? requested : PROTOCOL_VERSIONS[0],
          capabilities: { tools: {} },
          serverInfo: { name: cx.manifest.server.name || cx.project.slug, version: '1.0.0' },
          instructions: serverInstructions(cx),
        });
      }
      case 'ping':
        return rpcResult(id, {});
      case 'tools/list':
        return rpcResult(id, { tools: toolDefs(cx) });
      case 'tools/call':
        return rpcResult(id, await callTool(cx, params?.name, params?.arguments || {}));
      default:
        return rpcError(id, -32601, `Method not found: ${method}`);
    }
  } catch (e) {
    return rpcError(id, -32603, `Internal error: ${e.message}`);
  }
}

function serverInstructions(cx) {
  const m = cx.manifest;
  return [
    `${m.server.name}: ${m.server.description}`,
    `Generated by makeittalk.dev from ${cx.project.source_url || 'pasted documentation'}. `
    + `Base API: ${m.server.base_url}. Every tool maps to a real HTTP endpoint of that API. `
    + `If no purpose-built tool fits, use api_call with an explicit method and path.`,
  ].join('\n\n');
}

function toolDefs(cx) {
  const defs = cx.manifest.tools.map((t) => ({
    name: t.name,
    description: t.description + (t.provenance?.url ? `\n(Documented at ${t.provenance.url})` : ''),
    inputSchema: t.input_schema,
  }));
  defs.push({
    name: 'api_call',
    description: `Escape hatch: call any ${cx.manifest.server.base_url} endpoint directly. Use the purpose-built tools first.`
      + (cx.project.allow_delete ? '' : ' DELETE is refused on this server.'),
    inputSchema: {
      type: 'object',
      properties: {
        method: { type: 'string', enum: cx.project.allow_delete ? ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'] : ['GET', 'POST', 'PUT', 'PATCH'] },
        path: { type: 'string', description: 'Path starting with /, e.g. /v1/things' },
        query: { type: 'object', description: 'Query string parameters', additionalProperties: true },
        body: { type: 'object', description: 'JSON request body', additionalProperties: true },
      },
      required: ['method', 'path'],
      additionalProperties: false,
    },
  });
  return defs;
}

async function callTool(cx, name, args) {
  const meterOk = await meterToolCall(cx);
  if (!meterOk) {
    return errText(`Monthly tool-call limit reached for this makeittalk plan. Upgrade at ${cx.env.APP_ORIGIN || 'https://makeittalk.dev'}/pricing.`);
  }

  let built;
  if (name === 'api_call') {
    built = buildApiCall(cx, args);
  } else {
    const tool = cx.manifest.tools.find((t) => t.name === name);
    if (!tool) return errText(`Unknown tool: ${name}`);
    try {
      built = buildRequest(cx.manifest, tool, args);
    } catch (e) {
      return errText(e.message);
    }
  }
  if (built.error) return errText(built.error);

  let creds = null;
  if (cx.manifest.auth?.type !== 'none') {
    if (!cx.project.creds_enc) {
      return errText(`No credentials stored for "${cx.project.slug}". The project owner must add them at ${cx.env.APP_ORIGIN || 'https://makeittalk.dev'}/app.`);
    }
    creds = await decryptJson(cx.env.ENCRYPTION_KEY, cx.project.creds_enc);
  }

  try {
    const authed = await applyAuth({
      manifest: cx.manifest, creds, projectId: cx.project.id,
      url: built.url, headers: { Accept: 'application/json', ...built.headers },
    });
    let res = await fetch(authed.url, { method: built.method, headers: authed.headers, body: built.body });
    if (res.status === 401 && cx.manifest.auth?.type === 'oauth2_client_credentials') {
      invalidateOauthToken(cx.project.id);
      const retried = await applyAuth({
        manifest: cx.manifest, creds, projectId: cx.project.id,
        url: built.url, headers: { Accept: 'application/json', ...built.headers },
      });
      res = await fetch(retried.url, { method: built.method, headers: retried.headers, body: built.body });
    }
    const text = await res.text();
    let rendered = text;
    try { rendered = JSON.stringify(JSON.parse(text), null, 2); } catch { /* not JSON */ }
    const summary = `HTTP ${res.status} ${built.method} ${new URL(built.url).pathname}`;
    return {
      content: [{ type: 'text', text: `${summary}\n${clampStr(rendered, RESPONSE_CHAR_LIMIT)}` }],
      isError: !res.ok,
    };
  } catch (e) {
    return errText(`Request to the target API failed: ${e.message}`);
  }
}

function buildApiCall(cx, args) {
  const method = String(args.method || 'GET').toUpperCase();
  if (method === 'DELETE' && !cx.project.allow_delete) {
    return { error: 'DELETE is refused on this server (create-first by design). The project owner can enable it in settings.' };
  }
  if (!['GET', 'POST', 'PUT', 'PATCH', 'DELETE'].includes(method)) return { error: `Unsupported method ${method}` };
  const path = String(args.path || '');
  if (!path.startsWith('/')) return { error: 'path must start with /' };
  const url = new URL(cx.manifest.server.base_url + path);
  for (const [k, v] of Object.entries(args.query || {})) {
    if (v !== undefined && v !== null) url.searchParams.set(k, String(v));
  }
  const headers = {};
  let body;
  if (method !== 'GET' && args.body && typeof args.body === 'object') {
    headers['Content-Type'] = 'application/json';
    body = JSON.stringify(args.body);
  }
  return { url: url.toString(), method, headers, body };
}

const errText = (text) => ({ content: [{ type: 'text', text: `Error: ${text}` }], isError: true });

// Per-owner monthly tool-call metering. Returns false when over quota.
async function meterToolCall(cx) {
  const owner = await cx.env.DB.prepare('SELECT * FROM users WHERE id = ?').bind(cx.project.user_id).first();
  const plan = planFor(owner);
  const month = monthKey();
  await cx.env.DB.prepare(
    `INSERT INTO usage_months (user_id, month, tool_calls) VALUES (?, ?, 1)
     ON CONFLICT(user_id, month) DO UPDATE SET tool_calls = tool_calls + 1`
  ).bind(cx.project.user_id, month).run();
  const row = await cx.env.DB.prepare('SELECT tool_calls FROM usage_months WHERE user_id = ? AND month = ?')
    .bind(cx.project.user_id, month).first();
  return (row?.tool_calls || 0) <= plan.tool_calls_per_month;
}

const rpcResult = (id, result) => ({ jsonrpc: '2.0', id, result });
const rpcError = (id, code, message) => ({ jsonrpc: '2.0', id, error: { code, message } });

// Dashboard "try it" path: the owner runs a tool without MCP framing.
export async function runProjectTool(env, project, name, args) {
  const cx = { env, ctx: null, project, manifest: JSON.parse(project.manifest) };
  return callTool(cx, name, args || {});
}
